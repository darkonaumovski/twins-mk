import { fileURLToPath, URL } from 'node:url';
import { defineConfig } from 'vite';

/**
 * Bundles the push reminder code (src/server) into one dependency-free ES module for the
 * Supabase Edge Function: `npm run build:functions`. The result is committed, so deploying
 * the function needs no build step; a test checks that it matches the source.
 */
const HEADER = '// Generated by `npm run build:functions` from src/server/index.ts. Do not edit; change the source and rebuild.\n';

export default defineConfig({
  plugins: [
    {
      name: 'generated-header',
      generateBundle(_options, bundle) {
        for (const chunk of Object.values(bundle)) if (chunk.type === 'chunk') chunk.code = HEADER + chunk.code;
      },
    },
  ],
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  build: {
    outDir: 'supabase/functions/_shared',
    emptyOutDir: false,
    copyPublicDir: false,
    minify: false,
    reportCompressedSize: false,
    lib: {
      entry: fileURLToPath(new URL('./src/server/index.ts', import.meta.url)),
      formats: ['es'],
      fileName: () => 'reminders.js',
    },
  },
});
